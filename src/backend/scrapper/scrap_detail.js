const fetchDetails = (titleId) => {
    return new Promise((resolve, reject) => {
        const options = {
            method: 'GET',
            hostname: 'netflix-api8.p.rapidapi.com',
            port: null,
            path: `/api/title/details?titleId=${titleId}`,
            headers: {
                'x-rapidapi-key': 'f74337cc20msha7c357b7d45ad07p14916bjsn0c7df6f239ed',
                'x-rapidapi-host': 'netflix-api8.p.rapidapi.com'
            }
        };

        const req = http.request(options, (res) => {
            const chunks = [];

            res.on('data', (chunk) => {
                chunks.push(chunk);
            });

            res.on('end', () => {
                const body = Buffer.concat(chunks);
                resolve({ [titleId]: JSON.parse(body.toString()) });
            });
        });

        req.on('error', (e) => {
            reject(e);
        });

        req.end();
    });
};

